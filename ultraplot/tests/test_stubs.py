import ast
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from ultraplot.internals.docstring import _snippet_manager

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "ultraplot"
GENERATED_HEADER = "# @generated by tools/generate_stubs.py; do not edit"
PLACEHOLDER_PATTERN = re.compile(r"%\(([^)]+)\)s")


def _generated_stubs():
    return sorted(
        path
        for path in PACKAGE.rglob("*.pyi")
        if path.read_text(encoding="utf-8").startswith(GENERATED_HEADER)
    )


def _type_checking_imports(path):
    """Return the names imported inside a ``TYPE_CHECKING`` guard."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    names = set()
    for node in tree.body:
        if not isinstance(node, ast.If):
            continue
        test = node.test
        if not (isinstance(test, ast.Name) and test.id == "TYPE_CHECKING") and not (
            isinstance(test, ast.Attribute) and test.attr == "TYPE_CHECKING"
        ):
            continue
        for statement in ast.walk(node):
            if isinstance(statement, (ast.Import, ast.ImportFrom)):
                names.update(alias.asname or alias.name for alias in statement.names)
    return names


def _top_level_imports(path):
    """Return the names imported at module scope."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    return {
        alias.asname or alias.name
        for node in tree.body
        if isinstance(node, (ast.Import, ast.ImportFrom))
        for alias in node.names
    }


def test_generated_stubs_are_current():
    pyrefly = shutil.which("pyrefly")
    if pyrefly is None:
        pytest.skip("stub freshness requires the optional `typing` dependencies")
    env = os.environ.copy()
    env.setdefault("MPLCONFIGDIR", "/tmp/ultraplot-matplotlib")
    result = subprocess.run(
        [
            sys.executable,
            str(ROOT / "tools" / "generate_stubs.py"),
            "--check",
            "--pyrefly",
            pyrefly,
        ],
        cwd=ROOT,
        env=env,
        check=True,
        capture_output=True,
        text=True,
    )
    assert "source modules and their stubs" in result.stdout
    assert "all up to date" in result.stdout


def test_generated_stub_signatures_are_fully_annotated():
    missing = []
    for path in _generated_stubs():
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if node.returns is None:
                missing.append(f"{path.relative_to(ROOT)}:{node.lineno}: return")
            arguments = (
                *node.args.posonlyargs,
                *node.args.args,
                *node.args.kwonlyargs,
                node.args.vararg,
                node.args.kwarg,
            )
            for argument in arguments:
                if (
                    argument is not None
                    and argument.arg not in {"self", "cls"}
                    and argument.annotation is None
                ):
                    missing.append(
                        f"{path.relative_to(ROOT)}:{node.lineno}: {argument.arg}"
                    )
    assert not missing, "Unannotated generated signatures:\n" + "\n".join(missing)


def test_generated_stubs_are_valid_and_docstrings_are_expanded():
    stubs = _generated_stubs()
    assert stubs

    unresolved = []
    for path in stubs:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if not isinstance(
                node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
            ):
                continue
            doc = ast.get_docstring(node, clean=False) or ""
            for key in PLACEHOLDER_PATTERN.findall(doc):
                try:
                    _snippet_manager[key]
                except KeyError:
                    continue
                unresolved.append(f"{path.relative_to(ROOT)}:{node.lineno}: {key}")

    assert not unresolved, "Registered docstring placeholders remain:\n" + "\n".join(
        unresolved
    )


def test_root_stub_exposes_lazy_public_imports():
    source_names = _type_checking_imports(PACKAGE / "__init__.py")
    stub_names = _top_level_imports(PACKAGE / "__init__.pyi")

    assert source_names
    assert not source_names - stub_names


def test_generated_stubs_include_compact_runtime_docstrings():
    plot_stub = PACKAGE / "axes" / "plot.pyi"
    plot_tree = ast.parse(plot_stub.read_text(encoding="utf-8"))
    plot_doc = ""
    for node in ast.walk(plot_tree):
        if isinstance(node, ast.FunctionDef) and node.name == "plot":
            plot_doc = ast.get_docstring(node) or ""
            break
    assert "Plot standard lines" in plot_doc
    assert "Parameters" in plot_doc
    assert "Full API documentation" in plot_doc
    assert "Matplotlib documentation" not in plot_doc
    assert len(plot_doc) < 8000
    assert "=====================\nultraplot documentation" not in plot_doc
    assert ":class:`~pandas.DataFrame`" not in plot_doc

    grid_stub = PACKAGE / "gridspec.pyi"
    grid_tree = ast.parse(grid_stub.read_text(encoding="utf-8"))
    twiny_doc = ""
    for node in ast.walk(grid_tree):
        if isinstance(node, ast.FunctionDef) and node.name == "twiny":
            twiny_doc = ast.get_docstring(node) or ""
            break
    assert "for every axes in the grid" in twiny_doc


def test_long_hover_docstrings_are_compact_and_linked():
    ui_tree = ast.parse((PACKAGE / "ui.pyi").read_text(encoding="utf-8"))
    subplots = next(
        node
        for node in ui_tree.body
        if isinstance(node, ast.FunctionDef) and node.name == "subplots"
    )
    doc = ast.get_docstring(subplots) or ""
    assert len(doc) < 8000
    assert "%(figure.figure)s" not in doc
    assert "- `array`" in doc
    assert "- `nrows, ncols`" in doc
    assert (
        "[Full API documentation](https://ultraplot.readthedocs.io/en/stable/"
        "api/ultraplot.ui.subplots.html)" in doc
    )
    assert "Returns\n-------" not in doc


def test_plot_stub_exposes_static_signature():
    """The dynamic plot wrapper should retain its useful public call shape."""
    tree = ast.parse((PACKAGE / "axes" / "plot.pyi").read_text(encoding="utf-8"))
    plot_axes = next(
        node
        for node in tree.body
        if isinstance(node, ast.ClassDef) and node.name == "PlotAxes"
    )
    plot = next(
        node
        for node in plot_axes.body
        if isinstance(node, ast.FunctionDef) and node.name == "plot"
    )

    assert ast.unparse(plot.args.vararg.annotation) == "Any"
    assert [argument.arg for argument in plot.args.kwonlyargs] == [
        "scalex",
        "scaley",
        "data",
    ]
    assert ast.unparse(plot.args.kwarg.annotation) == "Any"
    assert ast.unparse(plot.returns) == "list[Any]"


def test_subplot_grid_stub_preserves_axes_indexing_chain():
    """Integer indexing must lead static analyzers from a grid to an axes."""
    grid_stub = PACKAGE / "gridspec.pyi"
    tree = ast.parse(grid_stub.read_text(encoding="utf-8"))
    grid = next(
        node
        for node in tree.body
        if isinstance(node, ast.ClassDef) and node.name == "SubplotGrid"
    )
    assert "paxes.PlotAxes" in {ast.unparse(base) for base in grid.bases}
    getitems = [
        node
        for node in grid.body
        if isinstance(node, ast.FunctionDef) and node.name == "__getitem__"
    ]
    assert len(getitems) >= 2
    assert any(
        ast.unparse(node.args.args[1].annotation) == "int"
        and ast.unparse(node.returns) == "paxes.Axes"
        for node in getitems
    )
