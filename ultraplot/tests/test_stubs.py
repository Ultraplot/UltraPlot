import ast
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from ultraplot.internals.docstring import _snippet_manager

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "ultraplot"
GENERATED_HEADER = "# @generated by tools/generate_stubs.py; do not edit"
PLACEHOLDER_PATTERN = re.compile(r"%\(([^)]+)\)s")


def _generated_stubs():
    return sorted(
        path
        for path in PACKAGE.rglob("*.pyi")
        if path.read_text(encoding="utf-8").startswith(GENERATED_HEADER)
    )


def _type_checking_imports(path):
    """Return the names imported inside a ``TYPE_CHECKING`` guard."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    names = set()
    for node in tree.body:
        if not isinstance(node, ast.If):
            continue
        test = node.test
        if not (isinstance(test, ast.Name) and test.id == "TYPE_CHECKING") and not (
            isinstance(test, ast.Attribute) and test.attr == "TYPE_CHECKING"
        ):
            continue
        for statement in ast.walk(node):
            if isinstance(statement, (ast.Import, ast.ImportFrom)):
                names.update(alias.asname or alias.name for alias in statement.names)
    return names


def _top_level_imports(path):
    """Return the names imported at module scope."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    return {
        alias.asname or alias.name
        for node in tree.body
        if isinstance(node, (ast.Import, ast.ImportFrom))
        for alias in node.names
    }


def test_generated_stubs_are_current():
    pyrefly = shutil.which("pyrefly")
    if pyrefly is None:
        pytest.skip("stub freshness requires the optional `typing` dependencies")
    env = os.environ.copy()
    env.setdefault("MPLCONFIGDIR", "/tmp/ultraplot-matplotlib")
    result = subprocess.run(
        [
            sys.executable,
            str(ROOT / "tools" / "generate_stubs.py"),
            "--check",
            "--pyrefly",
            pyrefly,
        ],
        cwd=ROOT,
        env=env,
        check=True,
        capture_output=True,
        text=True,
    )
    assert "source modules and their stubs" in result.stdout
    assert "all up to date" in result.stdout


def test_generated_stub_signatures_are_fully_annotated():
    missing = []
    for path in _generated_stubs():
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if node.returns is None:
                missing.append(f"{path.relative_to(ROOT)}:{node.lineno}: return")
            arguments = (
                *node.args.posonlyargs,
                *node.args.args,
                *node.args.kwonlyargs,
                node.args.vararg,
                node.args.kwarg,
            )
            for argument in arguments:
                if (
                    argument is not None
                    and argument.arg not in {"self", "cls"}
                    and argument.annotation is None
                ):
                    missing.append(
                        f"{path.relative_to(ROOT)}:{node.lineno}: {argument.arg}"
                    )
    assert not missing, "Unannotated generated signatures:\n" + "\n".join(missing)


def test_generated_stubs_are_valid_and_docstrings_are_expanded():
    stubs = _generated_stubs()
    assert stubs

    unresolved = []
    for path in stubs:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if not isinstance(
                node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
            ):
                continue
            doc = ast.get_docstring(node, clean=False) or ""
            for key in PLACEHOLDER_PATTERN.findall(doc):
                try:
                    _snippet_manager[key]
                except KeyError:
                    continue
                unresolved.append(f"{path.relative_to(ROOT)}:{node.lineno}: {key}")

    assert not unresolved, "Registered docstring placeholders remain:\n" + "\n".join(
        unresolved
    )


def test_root_stub_exposes_lazy_public_imports():
    source_names = _type_checking_imports(PACKAGE / "__init__.py")
    stub_names = _top_level_imports(PACKAGE / "__init__.pyi")

    assert source_names
    assert not source_names - stub_names
